def check_1D_orthonormality(wf_1D: Dict[str, Any]) -> Dict[str, Any]:
    """
    Проверка ортонормальности 1D-волновых функций.
    
    ФОРМУЛА:
        S_ij = ∫ ψ_i(x)·ψ_j(x) dx = δ_ij
    
    ВОЗВРАЩАЕТ:
        {'S': matrix, 'max_dev': float}
    """
    x = wf_1D['x']
    psi = wf_1D['psi']
    n_states = psi.shape[1]

    trapezoid = getattr(np, 'trapezoid', np.trapz)
    S = np.zeros((n_states, n_states))
    for i in range(n_states):
        for j in range(n_states):
            S[i, j] = trapezoid(psi[:, i] * psi[:, j], x)

    I = np.eye(n_states)
    max_dev = np.max(np.abs(S - I))

    return {'S': S, 'max_dev': max_dev}


def build_4D_wave_function(wf_1D: Dict[str, Any],
                            n_tuple: Tuple[int, int, int, int]) -> Dict[str, Any]:
    """
    Построение 4D-волновой функции через произведение 1D.
    
    ПАРАМЕТРЫ:
        wf_1D — словарь с 1D-функциями
        n_tuple = (n₁, n₂, n₃, n₄)
    
    ВОЗВРАЩАЕТ:
        {'psi_list': list of 4 arrays, 'E_4D': float, 'n_tuple': tuple}
    """
    n1, n2, n3, n4 = n_tuple
    psi = wf_1D['psi']
    E = wf_1D['E']

    psi_list = [psi[:, n1], psi[:, n2], psi[:, n3], psi[:, n4]]
    E_4D = E[n1] + E[n2] + E[n3] + E[n4]

    return {
        'psi_list': psi_list,
        'E_4D': E_4D,
        'n_tuple': n_tuple,
    }


def check_4D_normalization(wf_1D: Dict[str, Any],
                            n_tuple: Tuple[int, int, int, int]) -> Dict[str, Any]:
    """
    Проверка нормировки 4D-волновой функции.
    
    ФОРМУЛА:
        ∫∫∫∫ |Ψ|² dV = (∫|ψ₁|²dx₁)·(∫|ψ₂|²dx₂)·(∫|ψ₃|²dx₃)·(∫|ψ₄|²dx₄)
                      = 1·1·1·1 = 1
    
    ВОЗВРАЩАЕТ:
        {'norm_4D': float}
    """
    x = wf_1D['x']
    psi = wf_1D['psi']
    n1, n2, n3, n4 = n_tuple

    trapezoid = getattr(np, 'trapezoid', np.trapz)

    norm1 = trapezoid(psi[:, n1]**2, x)
    norm2 = trapezoid(psi[:, n2]**2, x)
    norm3 = trapezoid(psi[:, n3]**2, x)
    norm4 = trapezoid(psi[:, n4]**2, x)

    norm_4D = norm1 * norm2 * norm3 * norm4

    return {'norm_4D': norm_4D}


def compute_4D_spectrum_via_wave_functions(wf_1D: Dict[str, Any],
                                            n_max: int = 8) -> Dict[str, Any]:
    """
    Полный 4D-спектр через 1D-волновые функции.
    
    ВОЗВРАЩАЕТ:
        {'E_4D_all': array, 'unique_E': array, 'counts': array}
    """
    E_1D = wf_1D['E'][:n_max]

    E_4D_all = []
    for combo in product(range(n_max), repeat=4):
        E_total = sum(E_1D[n] for n in combo)
        E_4D_all.append(E_total)

    E_4D_all = np.array(sorted(E_4D_all))

    E_4D_rounded = np.round(E_4D_all, 3)
    unique_E, counts = np.unique(E_4D_rounded, return_counts=True)

    return {
        'E_4D_all': E_4D_all,
        'unique_E': unique_E,
        'counts': counts,
    }


def compute_4D_matrix_elements(wf_1D: Dict[str, Any],
                                n_tuple: Tuple[int, int, int, int],
                                ops: List[str] = None) -> Dict[str, Any]:
    """
    Вычисление матричных элементов 4D-операторов.
    
    ОПЕРАТОРЫ:
        'x'  → ⟨x_i⟩
        'x2' → ⟨x_i²⟩, Δx_i²
        'p2' → ⟨p_i²⟩
    
    ВОЗВРАЩАЕТ:
        dict {op_name: value}
    
    ФИЗИЧЕСКИЙ СМЫСЛ:
        Δx_i·Δp_i ≥ ħ/2 = 0.5 (принцип неопределённости)
    """
    if ops is None:
        ops = ['x', 'x2', 'p2']

    x = wf_1D['x']
    psi = wf_1D['psi']
    n1, n2, n3, n4 = n_tuple
    dx = x[1] - x[0]

    trapezoid = getattr(np, 'trapezoid', np.trapz)

    results = {}
    psi_n = [psi[:, n1], psi[:, n2], psi[:, n3], psi[:, n4]]

    for i, psi_i in enumerate(psi_n):
        if 'x' in ops:
            x_mean = trapezoid(psi_i**2 * x, x)
            results[f'<x_{i+1}>'] = x_mean

        if 'x2' in ops:
            x2_mean = trapezoid(psi_i**2 * x**2, x)
            results[f'<x_{i+1}²>'] = x2_mean
            results[f'Δx_{i+1}²'] = x2_mean - results[f'<x_{i+1}>']**2

        if 'p2' in ops:
            psi_second = np.gradient(np.gradient(psi_i, dx), dx)
            p2_mean = -trapezoid(psi_i * psi_second, x)
            results[f'<p_{i+1}²>'] = p2_mean

        if 'x2' in ops and 'p2' in ops:
            dx_i = np.sqrt(results[f'Δx_{i+1}²'])
            dp_i = np.sqrt(results[f'<p_{i+1}²>'])
            results[f'Δx_{i+1}·Δp_{i+1}'] = dx_i * dp_i

    return results


