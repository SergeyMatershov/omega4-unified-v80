def n_poly(k: int) -> int:
    """
    Мастер-полином n(k).
    
    ФОРМУЛА:
        n(k) = (103k⁴ − 370k³ + 101k² + 478k) / 12
    
    ПАРАМЕТРЫ:
        k — целое число (может быть отрицательным)
    
    ВОЗВРАЩАЕТ:
        n(k) — целое число
    
    ПРИМЕРЫ:
        >>> n_poly(-4)   # Рамануджан
        4146
        >>> n_poly(1)    # SU(26)
        26
        >>> n_poly(3)    # SU(58)
        58
    """
