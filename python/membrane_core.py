def run_1D_convergence(a: float = 7.0,
                        L: float = 30.0,
                        N_list: List[int] = None) -> Dict[str, Any]:
    """
    Проверка сходимости 1D-энергий к аналитическим.
    
    МЕТОД:
        Для каждого N вычисляет max|E_num − E_ana| и показывает,
        что ошибка убывает как O(dx²).
    
    ПАРАМЕТРЫ:
        a — параметр (по умолчанию 7.0)
        L — полуширина (по умолчанию 30)
        N_list — список N (по умолчанию [200, 400, 800, 1600, 3200])
    
    ВОЗВРАЩАЕТ:
        {
          'results': [
            {'N': int, 'dx': float, 'max_dev': float, 'ratio': float},
            ...
          ],
          'E_ana': array
        }
    """
    if N_list is None:
        N_list = [200, 400, 800, 1600, 3200]

    E_ana = spectrum_PT(a)
    results = []

    for N in N_list:
        wf = get_1D_wave_functions(a=a, L=L, N=N,
                                    n_states=len(E_ana))
        E_num = wf['E']
        dx = 2 * L / N

        dev = np.abs(E_num - E_ana)
        max_dev = np.max(dev)
        ratio = max_dev / dx**2

        results.append({
            'N': N, 'dx': dx, 'max_dev': max_dev, 'ratio': ratio,
        })

    return {'results': results, 'E_ana': E_ana}


