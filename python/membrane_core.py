def solve_schrodinger_2D(a: float = 7.0,
                          L: float = 10.0,
                          N: int = 200,
                          n_eig: int = 15) -> Dict:
    """
    2D-решение через разреженные матрицы.
    
    ТРЕБУЕТ: scipy
    
    ПАРАМЕТРЫ:
        a — параметр Пёшля-Теллера
        L — полуширина области
        N — число точек (сетка N×N)
        n_eig — число собственных значений
    
    ВОЗВРАЩАЕТ:
        {'E': array, 'dx': float, 'N': int, 'L': float}
    
    ЧИСЛО СОСТОЯНИЙ: N² (например, 200² = 40000)
    """
    if not SCIPY_AVAILABLE:
        return {'error': 'scipy not available'}

    x = np.linspace(-L, L, N)
    dx = x[1] - x[0]

    V_1D = V_PT1(x, a)
    V_2D = V_1D[:, None] + V_1D[None, :]
    V_flat = V_2D.flatten()

    main_diag = 2.0 / dx**2 * np.ones(N)
    off_diag = -1.0 / dx**2 * np.ones(N - 1)
    T_1D = diags([main_diag, off_diag, off_diag], [0, 1, -1], shape=(N, N))

    I_N = eye(N, format='csr')
    T_2D = kron(T_1D, I_N) + kron(I_N, T_1D)

    H = T_2D + diags(V_flat, 0, format='csr')

    E, _ = eigsh(H, k=n_eig, which='SM')
    E = np.sort(E)

    return {'E': E, 'dx': dx, 'N': N, 'L': L}


def run_2D_convergence(a: float = 7.0) -> Dict:
    """
    Проверка сходимости 2D-спектра к 1D-сумме.
    
    МЕТОД:
        Для N ∈ {100, 200, 300} вычисляет 2D-спектр и сравнивает
        с 1D-суммой.
    
    ВОЗВРАЩАЕТ:
        {'results': [
            {'N': int, 'dx': float, 'time': float, 'max_dev': float, 'ratio': float},
            ...
        ]}
    
    ОЖИДАЕМЫЙ РЕЗУЛЬТАТ:
        ratio = max|ΔE|/dx² → const (например, ~34.4)
        Это подтверждает сходимость O(dx²).
    """
    if not SCIPY_AVAILABLE:
        return {'skipped': True}

    spec_1D = spectrum_PT(a)
    results = []

    for N in [100, 200, 300]:
        t0 = time.time()
        result = solve_schrodinger_2D(a, L=10.0, N=N)
        t_elapsed = time.time() - t0

        E_2D = result['E']
        E_expected = sorted([
            spec_1D[n1] + spec_1D[n2]
            for n1, n2 in product(range(len(spec_1D)), repeat=2)
        ])

        max_dev = max(abs(E_2D[i] - E_expected[i])
                      for i in range(min(len(E_2D), len(E_expected), 10)))
        ratio = max_dev / result['dx']**2

        results.append({
            'N': N, 'dx': result['dx'],
            'time': t_elapsed, 'max_dev': max_dev, 'ratio': ratio,
        })

    return {'results': results}


