def V_PT1(x: np.ndarray, a: float = 7.0) -> np.ndarray:
    """
    Потенциал Пёшля-Теллера (тип 1).
    
    ФОРМУЛА:
        V₁(x) = a² − a(a+1)·sech²(x)
    
    ══════════════════════════════════════════════════════════════════════
    ВАЖНО: формула идентична msusy_derivation.V_poschl_teller().
    Оставлено автономным для независимости модулей (мембрана vs SUSY).
    ══════════════════════════════════════════════════════════════════════
    
    ПАРАМЕТРЫ:
        x — координата (numpy array)
        a — параметр (по умолчанию 7.0)
    
    ВОЗВРАЩАЕТ:
        V₁(x) — значения потенциала
    
    ФИЗИЧЕСКИЙ СМЫСЛ:
        Это ПОТЕНЦИАЛ МЕМБРАНЫ вдоль одного измерения.
        При a = 7 глубина ямы = a(a+1) = 56.
    """
    return a**2 - a * (a + 1) / np.cosh(x)**2


def V_PT2(x: np.ndarray, a: float = 7.0) -> np.ndarray:
    """
    Потенциал Пёшля-Теллера (тип 2, SUSY-партнёр).
    
    ФОРМУЛА:
        V₂(x) = a² − a(a−1)·sech²(x)
    
    ФИЗИЧЕСКИЙ СМЫСЛ:
        Это ПАРТНЁРСКИЙ ПОТЕНЦИАЛ к V₁.
        V₁ и V₂ имеют ОДИНАКОВЫЙ спектр, кроме основного состояния.
    """
    return a**2 - a * (a - 1) / np.cosh(x)**2


def W_super(x: np.ndarray, a: float = 7.0) -> np.ndarray:
    """
    Суперпотенциал W(x).
    
    ФОРМУЛА:
        W(x) = a·tanh(x)
    
    ══════════════════════════════════════════════════════════════════════
    ВАЖНО: формула идентична msusy_derivation.W_superpotential().
    Оставлено автономным для независимости модулей (мембрана vs SUSY).
    ══════════════════════════════════════════════════════════════════════
    
    ФИЗИЧЕСКИЙ СМЫСЛ:
        Используется в факторизации Дарбу:
        A  = d/dx + W(x)
        A† = -d/dx + W(x)
        V₁ = W² − W'
        V₂ = W² + W'
    """
    return a * np.tanh(x)


def E_n_PT(n: int, a: float = 7.0) -> Optional[float]:
    """
    Аналитический спектр Пёшля-Теллера.
    
    ФОРМУЛА:
        E_n = a² − (a−n)²
    ...
    
    ══════════════════════════════════════════════════════════════════════
    ВАЖНО: формула идентична msusy_derivation.E_n_analytical().
    Оставлено автономным для независимости модулей (мембрана vs SUSY).
    ══════════════════════════════════════════════════════════════════════
    """
    if n > math.floor(a):
        return None
    return a**2 - (a - n)**2


def spectrum_PT(a: float = 7.0) -> np.ndarray:
    """
    Полный спектр Пёшля-Теллера (аналитически).
    
    ВОЗВРАЩАЕТ:
        array E_n для n = 0, ..., floor(a)
    
    ПРИМЕР:
        >>> spectrum_PT(7.0)
        array([ 0., 13., 24., 33., 40., 45., 48., 49.])
    
    ══════════════════════════════════════════════════════════════════════
    ВАЖНО: формула идентична msusy_derivation.spectrum_analytical().
    Оставлено автономным для независимости модулей (мембрана vs SUSY).
    ══════════════════════════════════════════════════════════════════════
    """
    n_max = math.floor(a)
    return np.array([E_n_PT(n, a) for n in range(n_max + 1)])


def sech2_parameter_s(V0: float, w: float = 1.0) -> float:
    """
    Параметр s для V(x) = −V₀ · sech²(x/w).
    
    ФОРМУЛА:
        s = (√(1 + 4·V₀·w²) − 1) / 2
    
    ФИЗИЧЕСКИЙ СМЫСЛ:
        s — число связанных состояний (округлённое вниз).
        Для V₀ = 56, w = 1: s = 7.
    """
    return (math.sqrt(1 + 4 * V0 * w**2) - 1) / 2


def E_n_sech2(n: int, V0: float, w: float = 1.0) -> Optional[float]:
    """
    Энергия уровня для sech²-потенциала.
    
    ФОРМУЛА:
        E_n = −(s − n)² / w²
    
    ПАРАМЕТРЫ:
        n — номер уровня
        V0 — глубина ямы
        w — ширина ямы
    """
    s = sech2_parameter_s(V0, w)
    if n > math.floor(s):
        return None
    return -(s - n)**2 / w**2


def spectrum_sech2(V0: float, w: float = 1.0) -> np.ndarray:
    """
    Полный спектр sech²-потенциала.
    
    ПРИМЕР:
        >>> spectrum_sech2(56, 1.0)
        array([-49., -36., -25., -16., -9., -4., -1., 0.])
    """
    s = sech2_parameter_s(V0, w)
    n_max = math.floor(s)
    return np.array([E_n_sech2(n, V0, w) for n in range(n_max + 1)])


