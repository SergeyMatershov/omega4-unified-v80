# ЧАСТЬ 4: ЧИСЛЕННОЕ РЕШЕНИЕ 1D
# ============================================================================
#
# ┌─────────────────────────────────────────────────────────────────────────┐
# │  ЧИСЛЕННОЕ РЕШЕНИЕ УРАВНЕНИЯ ШРЁДИНГЕРА                                 │
# ├─────────────────────────────────────────────────────────────────────────┤
# │                                                                         │
# │  УРАВНЕНИЕ:                                                             │
# │    −ψ''(x) + V(x)·ψ(x) = E·ψ(x)                                        │
# │                                                                         │
# │  МЕТОД: конечные разности, второй порядок точности                     │
# │                                                                         │
# │  ДИСКРЕТИЗАЦИЯ:                                                         │
# │    x_i = −L + i·dx,  dx = 2L/N,  i = 0, ..., N−1                      │
# │                                                                         │
# │    ψ''(x_i) ≈ (ψ_{i+1} − 2ψ_i + ψ_{i−1}) / dx²                        │
# │                                                                         │
# │  МАТРИЦА ГАМИЛЬТОНИАНА:                                                 │
# │    H_ii     = 2/dx² + V(x_i)                                           │
# │    H_{i,i+1} = −1/dx²                                                   │
# │    H_{i,i−1} = −1/dx²                                                   │
# │                                                                         │
# │  ┌─────────────────────────────────────────────────────────────────┐   │
# │  │                                                                 │   │
# │  │  H =                                                            │   │
# │  │  ┌─────────────────────────────────────────────────────────┐   │   │
# │  │  │ 2/dx²+V₁  −1/dx²    0        ...                     │   │   │
# │  │  │ −1/dx²    2/dx²+V₂  −1/dx²   ...                     │   │   │
# │  │  │  0        −1/dx²    2/dx²+V₃ ...                     │   │   │
# │  │  │ ...       ...       ...      ...                     │   │   │
# │  │  └─────────────────────────────────────────────────────────┘   │   │
# │  │                                                                 │   │
# │  └─────────────────────────────────────────────────────────────────┘   │
# │                                                                         │
# │  РЕШЕНИЕ:                                                               │
# │    np.linalg.eigh(H) → E, ψ                                            │
# │                                                                         │
# │  СХОДИМОСТЬ O(dx²):                                                     │
# │    max|E_num − E_ana| ∝ dx²                                            │
# │                                                                         │
# └─────────────────────────────────────────────────────────────────────────┘

def solve_schrodinger_1D(
    potential_fn: Callable,
    L: float = 20.0,
    N: int = 4000,
    n_eig: int = 12,
) -> Dict[str, Any]:
    """
    Численное решение 1D-уравнения Шрёдингера.
    
    ══════════════════════════════════════════════════════════════════════
    ИСПРАВЛЕНИЯ v2.1 (eigh_tridiagonal):
      • L уменьшено с 40 до 20 (потенциал sech² затухает к |x|>10)
      • N уменьшено с 8000 до 4000 (dx = 0.01, точность та же)
      • Используется eigh_tridiagonal вместо eigh:
          - в 10-100 раз быстрее (O(N) vs O(N³))
          - точнее для малых собственных значений
          - select_range → считаем только первые n_eig уровней
      • Fallback на np.linalg.eigh, если scipy нет
      • Sanity-check на NaN/Inf и вырожденность
    ══════════════════════════════════════════════════════════════════════
    """
    x = np.linspace(-L, L, N)
    dx = x[1] - x[0]

    if dx <= 0 or N < 10:
        raise ValueError(f"Некорректные параметры: L={L}, N={N}, dx={dx}")

    V = potential_fn(x)

    # ─── SANITY CHECK ────────────────────────────────────────────────
    if not np.all(np.isfinite(V)):
        raise RuntimeError(f"V(x) содержит NaN/Inf при L={L}, N={N}")

    diag = 2.0 / dx**2 + V
    off_diag = -1.0 / dx**2 * np.ones(N - 1)

    if not np.all(np.isfinite(diag)) or not np.all(np.isfinite(off_diag)):
        raise RuntimeError("Диагональ или вне-диагональ содержит NaN/Inf")

    H_range = float(np.max(diag) - np.min(diag))
    if H_range < 1e-10:
        raise RuntimeError(f"H вырождена: разброс = {H_range}")

    # ─── ДИАГОНАЛИЗАЦИЯ ──────────────────────────────────────────────
    if HAS_TRIDIAGONAL:
        # Только первые n_eig собственных значений (САМЫЕ НИЖНИЕ)
        E, psi = eigh_tridiagonal(
            diag, off_diag,
            select='i',                    # по индексу
            select_range=(0, n_eig - 1),   # первые n_eig
        )
    else:
        # Fallback: полная диагонализация
        H = np.diag(diag) + np.diag(off_diag, k=1) + np.diag(off_diag, k=-1)
        E, psi = np.linalg.eigh(H)
        E = E[:n_eig]
        psi = psi[:, :n_eig]

    # ─── ПРОВЕРКА: не все E = 0 ──────────────────────────────────────
    if np.all(np.abs(E) < 1e-10):
        raise RuntimeError(
            f"Все собственные значения ≈ 0! E={E[:5]}, "
            f"diag_range=({np.min(diag):.2f}, {np.max(diag):.2f})"
        )

    # ─── НОРМИРОВКА ──────────────────────────────────────────────────
    trapezoid = getattr(np, 'trapezoid', np.trapz)
    for i in range(psi.shape[1]):
        norm = np.sqrt(trapezoid(psi[:, i]**2, x))
        if norm > 1e-10:
            psi[:, i] /= norm

    return {
        'E': E,
        'psi': psi,
        'x': x,
        'dx': dx,
        'H_min': float(np.min(diag)),
        'H_max': float(np.max(diag)),
    }


def get_1D_wave_functions(a: float = 7.0,
                           L: float = 20.0,
                           N: int = 4000,
                           n_states: int = 8) -> Dict[str, Any]:
    """
    Численное решение 1D-уравнения Шрёдингера для мембраны.
    
    ══════════════════════════════════════════════════════════════════════
    ИСПРАВЛЕНИЯ v2.1 (eigh_tridiagonal):
      • L уменьшено с 30 до 20
      • N увеличено с 3000 до 4000 (dx = 0.01)
      • Используется eigh_tridiagonal (в 10-100× быстрее)
      • Fallback на np.linalg.eigh
      • Sanity-check на NaN/Inf и вырожденность
    ══════════════════════════════════════════════════════════════════════
    """
    x = np.linspace(-L, L, N)
    dx = x[1] - x[0]

    if dx <= 0 or N < 10:
        raise ValueError(f"Некорректные параметры: L={L}, N={N}, dx={dx}")

    V = V_PT1(x, a)

    # ─── SANITY CHECK ────────────────────────────────────────────────
    if not np.all(np.isfinite(V)):
        raise RuntimeError(f"V_PT1(x, a={a}) содержит NaN/Inf")

    diag = 2.0 / dx**2 + V
    off_diag = -1.0 / dx**2 * np.ones(N - 1)

    if not np.all(np.isfinite(diag)) or not np.all(np.isfinite(off_diag)):
        raise RuntimeError("Диагональ или вне-диагональ содержит NaN/Inf")

    H_range = float(np.max(diag) - np.min(diag))
    if H_range < 1e-10:
        raise RuntimeError(f"H вырождена: разброс = {H_range}")

    # ─── ДИАГОНАЛИЗАЦИЯ ──────────────────────────────────────────────
    if HAS_TRIDIAGONAL:
        E, psi = eigh_tridiagonal(
            diag, off_diag,
            select='i',
            select_range=(0, n_states - 1),
        )
    else:
        H = np.diag(diag) + np.diag(off_diag, k=1) + np.diag(off_diag, k=-1)
        E, psi = np.linalg.eigh(H)
        E = E[:n_states]
        psi = psi[:, :n_states]

    # ─── ПРОВЕРКА: не все E = 0 ──────────────────────────────────────
    if np.all(np.abs(E) < 1e-10):
        raise RuntimeError(
            f"Все собственные значения ≈ 0! E={E[:5]}, "
            f"a={a}, L={L}, N={N}, dx={dx}"
        )

    # ─── НОРМИРОВКА ──────────────────────────────────────────────────
    trapezoid = getattr(np, 'trapezoid', np.trapz)
    for i in range(psi.shape[1]):
        norm = np.sqrt(trapezoid(psi[:, i]**2, x))
        if norm > 1e-10:
            psi[:, i] /= norm

    return {
        'x': x,
        'psi': psi,
        'E': E,
        'N': N,
        'L': L,
        'dx': dx,
        'H_min': float(np.min(diag)),
        'H_max': float(np.max(diag)),
    }

def run_1D_spectrum(a: float = 7.0,
                     L: float = 20.0,
                     N: int = 4000) -> Dict:
    """
    Сравнение численного и аналитического 1D-спектра.
    
    ══════════════════════════════════════════════════════════════════════
    ИСПРАВЛЕНИЯ v2.1:
      • L=20, N=4000 (стабильные вычисления)
      • Правильное сравнение массивов РАЗНОЙ длины
      • Возвращает диагностику (H_min, H_max) и статус
      • Ловит исключения и возвращает 'error'
    ══════════════════════════════════════════════════════════════════════
    """
    try:
        result = solve_schrodinger_1D(
            potential_fn=lambda x: V_PT1(x, a),
            L=L, N=N, n_eig=10,
        )
    except Exception as e:
        return {
            'E_num': np.array([]),
            'E_ana': spectrum_PT(a),
            'max_dev': float('inf'),
            'error': str(e),
            'ok': False,
        }

    E_num = result['E']
    E_ana = spectrum_PT(a)

    # ─── ПРАВИЛЬНОЕ СРАВНЕНИЕ ────────────────────────────────────────
    n_compare = min(len(E_num), len(E_ana))
    if n_compare == 0:
        return {
            'E_num': E_num,
            'E_ana': E_ana,
            'max_dev': float('inf'),
            'error': 'нет общих уровней',
            'ok': False,
        }

    deviations = np.abs(E_num[:n_compare] - E_ana[:n_compare])
    max_dev = float(np.max(deviations))

    return {
        'E_num': E_num,
        'E_ana': E_ana,
        'deviations': deviations,
        'max_dev': max_dev,
        'n_compared': n_compare,
        'H_min': result.get('H_min'),
        'H_max': result.get('H_max'),
        'ok': max_dev < 0.01,
    }
