def build_4D_hamiltonian_basis(E_1D: np.ndarray,
                                n_basis: int) -> np.ndarray:
    """
    Построение 4D-гамильтониана в базисе тензорных произведений.
    
    МЕТОД:
        Диагональная матрица размером n_basis⁴ × n_basis⁴.
        H[i, i] = E_{n1} + E_{n2} + E_{n3} + E_{n4}
        где (n1, n2, n3, n4) — разложение индекса i.
    
    ПАРАМЕТРЫ:
        E_1D — 1D-спектр (массив)
        n_basis — размер базиса (обычно 8)
    
    ВОЗВРАЩАЕТ:
        H_4D — диагональная матрица (n_basis⁴ × n_basis⁴)
    """
    dim = n_basis**4
    H_4D = np.zeros((dim, dim))

    for idx, combo in enumerate(product(range(n_basis), repeat=4)):
        E_total = sum(E_1D[n] for n in combo)
        H_4D[idx, idx] = E_total

    return H_4D


def run_4D_spectrum(a: float = 7.0, n_basis: int = 8) -> Dict:
    """
    Расчёт 4D-спектра через базис тензорных произведений.
    
    ПАРАМЕТРЫ:
        a — параметр Пёшля-Теллера
        n_basis — размер базиса (по умолчанию 8)
    
    ВОЗВРАЩАЕТ:
        {
          'E_4D': array,
          'max_dev': float,
          'unique_E': list,
          'energy_counts': Counter,
          'n_unique': int,
          'n_total': int
        }
    
    РАЗМЕР: 8⁴ = 4096 состояний
    ПАМЯТЬ: ~134 МБ (для 4096×4096 float64)
    """
    spec_1D = spectrum_PT(a)
    H_4D = build_4D_hamiltonian_basis(spec_1D, n_basis)

    E_4D_all, _ = np.linalg.eigh(H_4D)

    E_expected = sorted([
        sum(spec_1D[n] for n in combo)
        for combo in product(range(len(spec_1D)), repeat=4)
    ])
    E_expected = np.array(E_expected)

    max_dev = np.max(np.abs(E_4D_all - E_expected))

    energy_counts = Counter(E_4D_all)
    unique_E = sorted(set(E_4D_all))

    return {
        'E_4D': E_4D_all,
        'max_dev': max_dev,
        'unique_E': unique_E,
        'energy_counts': energy_counts,
        'n_unique': len(unique_E),
        'n_total': n_basis**4,
    }


