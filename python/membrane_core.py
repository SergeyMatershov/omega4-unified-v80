# ЧАСТЬ 5: SUSY QM (ФАКТОРИЗАЦИЯ ДАРБУ)
# ============================================================================
#
# ┌─────────────────────────────────────────────────────────────────────────┐
# │  SUSY КВАНТОВАЯ МЕХАНИКА (SUSY QM)                                      │
# ├─────────────────────────────────────────────────────────────────────────┤
# │                                                                         │
# │  ИДЕЯ:                                                                  │
# │    Любой 1D-гамильтониан H = −d²/dx² + V(x) можно факторизовать:      │
# │      H = A†A                                                            │
# │    где A = d/dx + W(x), A† = −d/dx + W(x).                             │
# │                                                                         │
# │  СУПЕРПОТЕНЦИАЛ:                                                        │
# │    W(x) = a·tanh(x)                                                     │
# │                                                                         │
# │  ДВА ГАМИЛЬТОНИАНА:                                                     │
# │    H₁ = A†A = −d²/dx² + V₁(x)   с V₁ = W² − W'                        │
# │    H₂ = AA† = −d²/dx² + V₂(x)   с V₂ = W² + W'                        │
# │                                                                         │
# │  ИЗОСПЕКТРАЛЬНОСТЬ:                                                     │
# │    Spec(H₁) \ {E₀} = Spec(H₂)                                          │
# │                                                                         │
# │  СХЕМА:                                                                 │
# │                                                                         │
# │    ┌──────────────────────────────────────────────────────────────┐    │
# │    │                                                              │    │
# │    │   E_n                                                        │    │
# │    │    │                                                         │    │
# │    │  49├──── E₇ ────────────────── E₆ (партнёр)                │    │
# │    │  48├──── E₆ ────────────────── E₅ (партнёр)                │    │
# │    │  45├──── E₅ ────────────────── E₄ (партнёр)                │    │
# │    │  40├──── E₄ ────────────────── E₃ (партнёр)                │    │
# │    │  33├──── E₃ ────────────────── E₂ (партнёр)                │    │
# │    │  24├──── E₂ ────────────────── E₁ (партнёр)                │    │
# │    │  13├──── E₁ ────────────────── E₀ (партнёр)                │    │
# │    │   0├──── E₀ ──────── (нет партнёра)                        │    │
# │    │    └─────────────┬───────────────────────────┘              │    │
# │    │                  │                                           │    │
# │    │               H₁ (V₁)              H₂ (V₂)                 │    │
# │    │                                                              │    │
# │    └──────────────────────────────────────────────────────────────┘    │
# │                                                                         │
# │  ФИЗИЧЕСКИЙ СМЫСЛ:                                                      │
# │    • E₀ = 0 — ОСОБОЕ состояние (нет партнёра)                          │
# │    • SUSY НАРУШЕНА, если E₀ = 0                                        │
# │    • ВСЕ остальные уровни имеют партнёра                               │
# │                                                                         │
# │  ПРИМЕНЕНИЕ В Ω⁴:                                                       │
# │    • a = 7 → 8 состояний (n = 0..7)                                    │
# │    • ΔE = 2a − 1 = 13                                                   │
# │    • M_SUSY = ΔE · M_EW = 3.20 ТэВ                                     │
# │                                                                         │
# └─────────────────────────────────────────────────────────────────────────┘

def verify_darboux_factoring(a: float = 7.0,
                              N: int = 2000,
                              L: float = 40.0) -> Dict[str, Any]:
    """
    Проверка факторизации Дарбу: H = A†A.
    
    МЕТОД:
        Строит операторы A и A† как разреженные матрицы N×N,
        затем проверяет, что H₁ = A†A и H₂ = AA† эрмитовы.
    
    ПАРАМЕТРЫ:
        a — параметр (по умолчанию 7.0)
        N — число точек (по умолчанию 2000)
        L — полуширина (по умолчанию 40)
    
    ВОЗВРАЩАЕТ:
        {'herm1': bool, 'herm2': bool}
    
    ФИЗИЧЕСКИЙ СМЫСЛ:
        • Эрмитовость H₁ и H₂ — необходимое условие SUSY QM.
        • Если нарушена — факторизация не работает.
    """
    x = np.linspace(-L, L, N)
    dx = x[1] - x[0]
    W = W_super(x, a)

    # A = d/dx + W(x) — дискретизация
    A = np.diag(W)
    A += np.diag(0.5 / dx * np.ones(N - 1), k=1)
    A += np.diag(-0.5 / dx * np.ones(N - 1), k=-1)

    # A† = -d/dx + W(x) — дискретизация
    Adag = np.diag(W)
    Adag += np.diag(-0.5 / dx * np.ones(N - 1), k=1)
    Adag += np.diag(0.5 / dx * np.ones(N - 1), k=-1)

    H1 = Adag @ A
    H2 = A @ Adag

    herm1 = np.allclose(H1, H1.conj().T, atol=1e-6)
    herm2 = np.allclose(H2, H2.conj().T, atol=1e-6)

    return {'herm1': herm1, 'herm2': herm2}


def compute_susy_partners(wf_1D: Dict[str, Any],
                           a: float = 7.0) -> Dict[str, Any]:
    """
    Вычисление SUSY-партнёров через факторизацию Дарбу.
    
    ФОРМУЛА:
        ψ_n^(2) = A · ψ_{n+1}^(1) / √(E_{n+1}^(1) − E₀^(1))
    
    ПАРАМЕТРЫ:
        wf_1D — словарь {'x', 'psi', 'E', ...} из get_1D_wave_functions()
        a — параметр
    
    ВОЗВРАЩАЕТ:
        {
          'psi_partners': list of arrays,
          'energies_partners': list of floats,
          'S_partners': matrix (overlap),
          'max_dev': float,
          'isospectral': bool
        }
    
    ФИЗИЧЕСКИЙ СМЫСЛ:
        • ψ_n^(2) — партнёрские волновые функции
        • E_n^(2) = E_{n+1}^(1) — изоспектральность
        • Нарушение SUSY: E₀ = 0 (нет партнёра для вакуума)
    """
    x = wf_1D['x']
    psi = wf_1D['psi']
    E = wf_1D['E']
    n_states = psi.shape[1]
    dx = x[1] - x[0]

    trapezoid = getattr(np, 'trapezoid', np.trapz)

    W = W_super(x, a)
    E_0 = E[0]

    psi_partners = []
    energies_partners = []

    for n in range(n_states - 1):
        psi_n_plus_1 = psi[:, n + 1]
        E_n_plus_1 = E[n + 1]

        # A ψ = dψ/dx + W(x)·ψ
        psi_deriv = np.gradient(psi_n_plus_1, dx)
        A_psi = psi_deriv + W * psi_n_plus_1

        # Нормировка
        norm_factor = math.sqrt(E_n_plus_1 - E_0) if E_n_plus_1 > E_0 else 1.0
        psi_n_2 = A_psi / norm_factor

        # Численная нормировка
        norm = trapezoid(psi_n_2**2, x)
        if norm > 1e-10:
            psi_n_2 /= np.sqrt(norm)

        psi_partners.append(psi_n_2)
        energies_partners.append(E_n_plus_1)

    # Проверка ортонормальности партнёров
    n_partners = len(psi_partners)
    S_partners = np.zeros((n_partners, n_partners))
    for i in range(n_partners):
        for j in range(n_partners):
            S_partners[i, j] = trapezoid(psi_partners[i] * psi_partners[j], x)

    I = np.eye(n_partners)
    max_dev = np.max(np.abs(S_partners - I))

    # Проверка изоспектральности
    iso = np.allclose(E[1:n_states], np.array(energies_partners),
                       atol=1e-6, rtol=1e-6)

    return {
        'psi_partners': psi_partners,
        'energies_partners': energies_partners,
        'S_partners': S_partners,
        'max_dev': max_dev,
        'isospectral': iso,
    }


