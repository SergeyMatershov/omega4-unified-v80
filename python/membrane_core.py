def run_mass_spectrum(a: float = 7.0) -> Dict:
    """
    Спектр масс полей: m_n = M_EW · √(E_n/E_1).
    
    ВОЗВРАЩАЕТ:
        {'masses': list, 'E_1': float}
    """
    E_ana = spectrum_PT(a)
    E_1 = E_ana[1]

    masses = []
    for n, E_n in enumerate(E_ana):
        if n == 0:
            m_n = 0.0
        else:
            m_n = M_EW * math.sqrt(E_n / E_1)
        masses.append(m_n)

    return {'masses': masses, 'E_1': E_1}


def run_M_SUSY(a: float = 7.0) -> Dict:
    """
    M_SUSY = (2a − 1) · M_EW.
    
    ПРИ a = 7: M_SUSY = 13 · 246.22 = 3.20 ТэВ
    ПРИ a = 8: M_SUSY = 15 · 246.22 = 3.69 ТэВ
    """
    delta_E = 2 * a - 1
    M_SUSY = delta_E * M_EW

    return {'M_SUSY': M_SUSY, 'delta_E': delta_E}


def run_topology() -> Dict:
    """
    Топологические связи: a² = 49 и V₀ = 56.
    
    ВОЗВРАЩАЕТ:
        {'matches_a2': list, 'matches_V0': list}
    """
    candidates_a2 = {
        '2·h¹¹·β₁₂ + 1': 2 * H11 * BETA_12 + 1,
        'χ/22 + h²¹ + 12': CHI / 22 + H21 + 12,
        'n(3)/2 + 20': n_poly(3) / 2 + 20,
        'dim(SO(8)) + 21': 28 + 21,
        '7²': 7**2,
        'N_eff²': N_EFF_MEMBRANE**2,
    }

    matches_a2 = []
    for name, val in candidates_a2.items():
        if abs(val - 49) < 1e-10:
            matches_a2.append(name)

    candidates_V0 = {
        'a(a+1) = 7·8': 7 * 8,
        'χ/11 = 616/11': CHI / 11,
        'N_eff·(N_eff+1)': N_EFF_MEMBRANE * (N_EFF_MEMBRANE + 1),
        'gcd(|W(E₈)|, χ)': math.gcd(696729600, CHI),
    }

    matches_V0 = []
    for name, val in candidates_V0.items():
        if abs(val - 56) < 1e-10:
            matches_V0.append(name)

    return {'matches_a2': matches_a2, 'matches_V0': matches_V0}


def run_cosmology() -> Dict:
    """
    УПРОЩЁННАЯ космологическая проверка через χ.
    
    ВАЖНО: основной источник n_s — physics.Cosmology.
    Эта функция — кросс-проверка: показывает, что n_s получается
    из χ/10, а не только из полного инфляционного расчёта.
    
    Космологические следствия: N_e, n_s, r.
    
    ВОЗВРАЩАЕТ:
        {'N_e': float, 'n_s': float, 'r': float, 'dev_ns': float}
    """
    N_e = CHI / 10.0
    n_s = 1.0 - 2.0 / N_e
    r = 12.0 / N_e**2

    dev_ns = abs(n_s - N_S_OBS) / N_S_OBS * 100

    return {'N_e': N_e, 'n_s': n_s, 'r': r, 'dev_ns': dev_ns}


